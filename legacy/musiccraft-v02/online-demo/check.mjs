import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
import {webcrypto} from 'node:crypto';
const context={window:{},crypto:webcrypto,Blob,URL,setTimeout,clearTimeout,console,localStorage:{removeItem(){}},location:{reload(){}},fetch(){throw new Error('Online flow demo must not send requests');}};
vm.runInNewContext(await readFile('dist/browser-engine.js','utf8'),context);
const engine=context.window.MusicCraftOnline;
const api=engine.api;
assert.equal((await api('/api/config')).mode,'demo');
assert.equal((await api('/api/config')).voice_ready,false);
const missing=await api('/api/plans',{prompt:'用我的声音翻唱',controls:{task:'voice_cover'}});
assert.equal(missing.blockers.length,2);
const assets=await api('/api/demo-assets',{});
const plan=await api('/api/plans',{prompt:'保留主旋律，改成古风，加入古筝和弦乐。',controls:{task:'restyle',source_asset_id:assets.source.id,duration:10}});
assert.equal(plan.spec.style,'guofeng');assert.deepEqual(Array.from(plan.spec.instruments),['strings','guzheng']);assert.equal(plan.blockers.length,0);
await assert.rejects(api('/api/plans',{prompt:'改成流行',controls:{duration:100}}),/duration/);
const job=await api('/api/jobs',{plan_id:plan.id});
assert.equal((await api('/api/jobs',{plan_id:plan.id})).id,job.id);
let result;
for(let i=0;i<60;i++){result=await api('/api/jobs/'+job.id);if(result.status==='succeeded')break;await new Promise(r=>setTimeout(r,50));}
assert.equal(result.status,'succeeded');assert.equal(result.mode,'demo');assert.ok(result.steps.every(x=>x.status==='succeeded'));
const file=await fetch(engine.audioURL(result.output_asset_id));const audio=new DataView(await file.arrayBuffer());
assert.equal(audio.getUint32(0,false),0x52494646);assert.equal(audio.getUint32(40,true),10*16000*2);
await api('/api/jobs/'+job.id+'/pin',{});await api('/api/jobs/'+job.id+'/pin',{});
assert.equal((await api('/api/showcases')).showcases.length,1);assert.equal((await api('/api/jobs/'+job.id)).status,'succeeded');
const snapshot=JSON.stringify(result);
const cover=await api('/api/plans',{prompt:'用我的声音翻唱',parent_job_id:job.id,controls:{task:'voice_cover',voice_asset_id:assets.voice.id}});
assert.equal(cover.spec.source_asset_id,result.output_asset_id);assert.equal(cover.spec.task,'voice_cover');assert.equal(cover.blockers.length,0);
const canceled=await api('/api/jobs',{plan_id:cover.id});await api('/api/jobs/'+canceled.id+'/cancel',{});
await new Promise(r=>setTimeout(r,100));assert.equal((await api('/api/jobs/'+canceled.id)).status,'canceled');
assert.equal(JSON.stringify(await api('/api/jobs/'+job.id)),snapshot);
new vm.Script(await readFile('dist/app.js','utf8'));
const html=await readFile('dist/index.html','utf8');assert.ok(html.includes('/browser-engine.js'));assert.ok(html.includes('合成占位'));
console.log('Online demo checks passed: plan validation, both routes, audio, cancellation, version integrity, pinning, and no server requests.');
